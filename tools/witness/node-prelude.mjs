// Node implementations of the prelude names in prelude/ulua.d.ts, and
// of the host fixtures of specs/blocks/corpus.md section 7.
// The node witness installs them before it loads a corpus program.

const FIXTURES = {
  hostAdd: () => (a, b) => a + b,
  hostConcat: () => (a, b) => a + b,
  hostNot: () => (b) => !b,
  hostLog: (output) => (text) => {
    output.push(`log:${text}`);
  },
};

export const FIXTURE_NAMES = Object.keys(FIXTURES);

// Parameter types and result type of each fixture (corpus.md section 7).
const SIGNATURES = {
  hostAdd: [["number", "number"], "number"],
  hostConcat: [["string", "string"], "string"],
  hostNot: [["boolean"], "boolean"],
  hostLog: [["string"], "void"],
};

// The host declarations of a grant list, in the format of abi.md
// section 6.3. This derivation is separate from ulua_declarations.
export function declarations(grants) {
  const lines = ["// Ulua host declarations. Generated by ulua_declarations."];
  for (const name of grants) {
    const [params, result] = SIGNATURES[name];
    lines.push(`declare function ${name}(${params.map((t, i) => `p${i}: ${t}`).join(", ")}): ${result};`);
  }
  return lines.join("\n") + "\n";
}

// grants: the fixture names of the entry's `grants` header.
export function install(output, grants = []) {
  globalThis.print = (text) => {
    output.push(String(text));
  };
  globalThis.Utf8 = Object.freeze({
    byteLength: (text) => Buffer.byteLength(text, "utf8"),
  });
  for (const name of FIXTURE_NAMES) delete globalThis[name];
  for (const name of grants) globalThis[name] = FIXTURES[name](output);
}
