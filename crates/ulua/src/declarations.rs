//! Deterministic TypeScript declarations from capability signatures.
use crate::*;
use std::{
    ffi::c_char,
    fmt::Write,
    panic::{AssertUnwindSafe, catch_unwind},
    ptr, slice,
};
fn type_name(tag: u32) -> &'static str {
    match tag {
        1 => "number",
        2 => "boolean",
        3 => "string",
        _ => "void",
    }
}
/// Write the declarations in grant order. A short buffer writes only the required byte length.
/// # Safety
/// Grants must be live. Buffer and length storage must cover their stated capacities.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn ulua_declarations(
    grants: *const *mut Capability,
    grant_count: usize,
    buffer: *mut c_char,
    capacity: usize,
    length: *mut usize,
) -> Status {
    if (grants.is_null() && grant_count != 0)
        || grant_count > isize::MAX as usize / size_of::<*mut Capability>()
    {
        return ULUA_INVALID_ARGUMENT;
    }
    // SAFETY: The caller supplies readable live grant pointers and serializes each context.
    unsafe {
        let grants = if grant_count == 0 {
            &[]
        } else {
            slice::from_raw_parts(grants, grant_count)
        };
        if grants.iter().any(|p| p.is_null()) {
            return ULUA_INVALID_ARGUMENT;
        }
        if grants.iter().any(|p| (*(**p).context).busy.get()) {
            return ULUA_BUSY;
        }
        if grants.iter().any(|p| (*(**p).context).poisoned.get()) {
            return ULUA_POISONED;
        }
        if length.is_null() || (buffer.is_null() && capacity != 0) || capacity > isize::MAX as usize
        {
            return ULUA_INVALID_ARGUMENT;
        }
        let answer = catch_unwind(AssertUnwindSafe(|| {
            let mut names = std::collections::HashSet::new();
            let mut text =
                String::from("// Ulua host declarations. Generated by ulua_declarations.\n");
            for &grant in grants {
                let capability = &*grant;
                let signature = &capability.state.signature;
                if !names.insert(signature.name.as_str()) {
                    return ULUA_INVALID_ARGUMENT;
                }
                let _ = write!(text, "declare function {}(", signature.name);
                for (i, t) in signature.parameters.iter().enumerate() {
                    if i != 0 {
                        text.push_str(", ");
                    }
                    let _ = write!(text, "p{i}: {}", type_name(*t));
                }
                let _ = writeln!(text, "): {};", type_name(signature.result));
            }
            length.write(text.len());
            if capacity < text.len() {
                return ULUA_INVALID_ARGUMENT;
            }
            ptr::copy_nonoverlapping(text.as_ptr().cast::<c_char>(), buffer, text.len());
            ULUA_OK
        }));
        match answer {
            Ok(status) => status,
            Err(_) => {
                for &grant in grants {
                    (*(*grant).context).poisoned.set(true);
                }
                ULUA_INTERNAL
            }
        }
    }
}
