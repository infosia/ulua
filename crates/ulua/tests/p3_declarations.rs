//! Direct declarations API tests compare the ABI with the independent Node fixture format.
// External ABI descriptors are non-exhaustive and require field assignments.
#![allow(clippy::field_reassign_with_default)]
#[path = "support/p3_declaration_text.rs"]
mod declarations;
#[path = "../../ulua_corpus/src/fixtures.rs"]
mod fixtures;

use std::{ffi::c_void, path::PathBuf, process::Command, ptr, time::Instant};
use ulua::*;
unsafe extern "C" fn no_call(_: *mut c_void, _: *const Value, _: usize, _: *mut Value) -> i32 {
    0
}
fn capability(c: *mut Context, name: &str, parameters: &[u32], result: u32) -> *mut Capability {
    let mut d = CapabilityDesc::default();
    d.name = name.as_ptr().cast();
    d.name_length = name.len();
    d.parameter_types = parameters.as_ptr();
    d.parameter_count = parameters.len();
    d.result_type = result;
    d.function = Some(no_call);
    let mut cap = ptr::null_mut();
    // SAFETY: The test owns all descriptor storage and serializes the live context.
    unsafe {
        assert_eq!(ulua_capability_new(c, &d, &mut cap), ULUA_OK);
    }
    cap
}
#[test]
fn declarations_exact_types_order_queries_revocation_and_node_reference() {
    let now = Instant::now();
    let mut c = ptr::null_mut();
    // SAFETY: The test owns writable context pointer storage.
    unsafe {
        assert_eq!(ulua_context_new(&mut c), ULUA_OK);
    }
    let grants = [
        capability(c, "hostVoid", &[], 0),
        capability(c, "hostNumber", &[1, 2, 3], 1),
        capability(c, "hostBoolean", &[2], 2),
        capability(c, "hostString", &[3], 3),
    ];
    let expected = "// Ulua host declarations. Generated by ulua_declarations.\ndeclare function hostVoid(): void;\ndeclare function hostNumber(p0: number, p1: boolean, p2: string): number;\ndeclare function hostBoolean(p0: boolean): boolean;\ndeclare function hostString(p0: string): string;\n";
    // SAFETY: Grants remain live throughout the serialized API calls; all outputs cover their capacities.
    unsafe {
        assert_eq!(declarations::text(&grants).unwrap(), expected);
        assert_eq!(declarations::text(&grants).unwrap(), expected);
        assert_eq!(ulua_capability_revoke(grants[1]), ULUA_OK);
        assert_eq!(declarations::text(&grants).unwrap(), expected);
        let reversed = [grants[3], grants[2], grants[1], grants[0]];
        let text = declarations::text(&reversed).unwrap();
        assert!(
            text.lines()
                .nth(1)
                .unwrap()
                .starts_with("declare function hostString")
        );
        assert_eq!(
            declarations::text(&[]).unwrap(),
            "// Ulua host declarations. Generated by ulua_declarations.\n"
        );
        let mut bytes = vec![77_u8; expected.len() - 1];
        let mut length = 999;
        assert_eq!(
            ulua_declarations(
                grants.as_ptr(),
                grants.len(),
                bytes.as_mut_ptr().cast(),
                bytes.len(),
                &mut length
            ),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(length, expected.len());
        assert!(bytes.iter().all(|b| *b == 77));
        length = 999;
        assert_eq!(
            ulua_declarations(
                [grants[0], grants[0]].as_ptr(),
                2,
                bytes.as_mut_ptr().cast(),
                bytes.len(),
                &mut length
            ),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(length, 999);
        assert!(bytes.iter().all(|b| *b == 77));
        let duplicate = capability(c, "hostVoid", &[], 0);
        assert_eq!(
            ulua_declarations(
                [grants[0], duplicate].as_ptr(),
                2,
                ptr::null_mut(),
                0,
                &mut length
            ),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(length, 999);
        assert_eq!(
            ulua_declarations(ptr::null(), 1, ptr::null_mut(), 0, &mut length),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(
            ulua_declarations(
                [ptr::null_mut()].as_ptr(),
                1,
                ptr::null_mut(),
                0,
                &mut length
            ),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(
            ulua_declarations(ptr::null(), 0, ptr::null_mut(), 1, &mut length),
            ULUA_INVALID_ARGUMENT
        );
        assert_eq!(
            ulua_declarations(ptr::null(), 0, ptr::null_mut(), 0, ptr::null_mut()),
            ULUA_INVALID_ARGUMENT
        );
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let mut f = fixtures::Fixtures::new();
        let signatures =
            fixtures::Fixtures::signatures(b"// grants: hostLog, hostConcat, hostNot, hostAdd")
                .unwrap();
        let grants = f.grants(c, &signatures).unwrap();
        let actual = declarations::text(&grants).unwrap();
        let node=Command::new("node").args(["--input-type=module","-e","import {pathToFileURL} from 'node:url'; const {declarations}=await import(pathToFileURL(process.argv[1]));process.stdout.write(declarations(['hostLog','hostConcat','hostNot','hostAdd']));"]).arg(root.join("tools/witness/node-prelude.mjs")).output().unwrap();
        assert!(
            node.status.success(),
            "{}",
            String::from_utf8_lossy(&node.stderr)
        );
        assert_eq!(actual, String::from_utf8(node.stdout).unwrap());
        assert_eq!(ulua_context_free(c), ULUA_OK);
    }
    eprintln!(
        "P3 declarations node_fixture_comparison=4 cost={:.3}s",
        now.elapsed().as_secs_f64()
    );
}
