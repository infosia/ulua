/// Source ceiling in bytes.
pub const SOURCE_CEILING: u64 = 64 * 1024;
/// Peak live Rust heap bytes per source byte, plus [`COMPILE_MEMORY_BASE`].
/// P5.4 measures the C ABI for 277 growth shapes at 16 KiB and 64 KiB.
/// The maximum was 58,408,757 / 65,536 for nested-empty-blocks in Debug.
/// This factor is that ratio times 1.25, rounded up. The timing witness asserts it.
/// The count excludes borrowed inputs, stack space, and native Luau allocations.
pub const COMPILE_MEMORY_FACTOR: usize = 1115;
/// Fixed peak live Rust heap allowance for one compiler call.
/// The largest small-source peak was 68,017 bytes for seven distinct empty classes in Debug.
/// This base is that peak times 1.25, rounded up.
pub const COMPILE_MEMORY_BASE: usize = 85022;
/// Generated bytes per source byte, above the fixed prelude.
/// This compiler limit applies to every emitted module.
pub const OUTPUT_FACTOR: usize = 80;
/// Bytes of the base strict-mode and library prelude, before selected method helpers.
pub const OUTPUT_PRELUDE_BYTES: usize = "--!strict\n".len() + emitter::LIBRARIES.len();
/// Bytes of the fixed promise and exception helpers for an async module.
/// Add these bytes to the base prelude for an async output bound.
pub const OUTPUT_ASYNC_PRELUDE_BYTES: usize = emitter::ASYNC_PRELUDE_BYTES;
/// Maximum generated statements on a forward path between interrupt points.
/// The O1 emitter calls a shared empty Luau function before statement 17.
pub const INTERRUPT_STATEMENTS: usize = 16;
/// Maximum executed VM instructions between interrupt callbacks.
/// The repaired P5.5 witness measures 34 instructions at 64 KiB under O1.
/// This bound retains the original maximum, 35 times 1.25, rounded up.
pub const INTERRUPT_INSTRUCTIONS: u64 = 44;
/// AST and parser depth ceiling.
pub const DEPTH_CEILING: u32 = 48;
/// Stack size for the complete compiler pipeline.
pub const COMPILER_STACK_BYTES: usize = 2 * 1024 * 1024;

/// Host limits for the safe compiler stages.
#[derive(Clone, Copy, Debug)]
#[non_exhaustive]
pub struct Limits {
    /// Maximum source length.
    pub max_source_bytes: u64,
    /// Maximum parser and AST depth.
    pub max_nesting_depth: u32,
}
impl Default for Limits {
    fn default() -> Self {
        Self {
            max_source_bytes: SOURCE_CEILING,
            max_nesting_depth: DEPTH_CEILING,
        }
    }
}

/// The first compiler violation.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct Diagnostic {
    /// Stable diagnostic code.
    pub code: &'static str,
    /// Source byte offset.
    pub offset: u64,
    /// One-based source line.
    pub line: u32,
    /// One-based byte column.
    pub column: u32,
    /// Human-readable message.
    pub message: String,
}
impl Diagnostic {
    pub(crate) fn at(
        source: &[u8],
        offset: usize,
        code: &'static str,
        message: impl Into<String>,
    ) -> Self {
        let offset = offset.min(source.len());
        let mut line = 1;
        let mut column = 1;
        let mut i = 0;
        while i < offset {
            match source[i] {
                b'\r' => {
                    line += 1;
                    column = 1;
                    if i + 1 < offset && source[i + 1] == b'\n' {
                        i += 1;
                    }
                }
                b'\n' => {
                    line += 1;
                    column = 1;
                }
                0xe2 if i + 2 < offset
                    && source[i + 1] == 0x80
                    && matches!(source[i + 2], 0xa8 | 0xa9) =>
                {
                    line += 1;
                    column = 1;
                    i += 2;
                }
                _ => {
                    column += 1;
                }
            }
            i += 1;
        }
        Self {
            code,
            offset: offset as u64,
            line,
            column,
            message: message.into(),
        }
    }
}

/// An export signature derived by the checker.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct Export {
    /// The TypeScript export name.
    pub name: String,
    /// ABI parameter type tags.
    pub parameters: Vec<u32>,
    /// ABI result type tag.
    pub result: u32,
}

/// Internal source and signatures for the runtime and corpus witness.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct Compiled {
    /// Host declaration names in chunk argument order.
    pub hosts: Vec<String>,
    /// Strict, generated Luau source.
    pub luau: String,
    /// Export signatures in source order.
    pub exports: Vec<Export>,
}

/// Parse, bound, check, and emit one module.
pub fn compile(source: &[u8], limits: Limits) -> Result<Compiled, Diagnostic> {
    compile_with_grants(source, limits, &[])
}

/// A host signature supplied by the compiler caller.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct HostSignature {
    /// Capability name.
    pub name: String,
    /// ABI parameter tags.
    pub parameters: Vec<u32>,
    /// ABI result tag.
    pub result: u32,
    /// The host starts a request with a Promise result.
    pub asynchronous: bool,
}
impl HostSignature {
    /// Construct a grant signature.
    pub fn new(name: impl Into<String>, parameters: Vec<u32>, result: u32) -> Self {
        Self {
            name: name.into(),
            parameters,
            result,
            asynchronous: false,
        }
    }
}
/// Compile with explicit host signatures, without ABI objects.
pub fn compile_with_grants(
    source: &[u8],
    limits: Limits,
    grants: &[HostSignature],
) -> Result<Compiled, Diagnostic> {
    compile_observed(
        source,
        limits,
        grants,
        OUTPUT_FACTOR,
        emitter::emit,
        |_, _| {},
    )
}

