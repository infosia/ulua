/// Measure each stage with a callback before and after its work.
/// This entry exists only in measurement builds; it uses the production pipeline.
#[cfg(feature = "measurements")]
pub fn measure_compile(
    source: &[u8],
    limits: Limits,
    observer: impl FnMut(&'static str, bool),
) -> Result<Compiled, Diagnostic> {
    compile_observed(source, limits, &[], OUTPUT_FACTOR, emitter::emit, observer)
}

/// Emit a typed template fixture beyond the checker bound, for native limit measurements only.
/// The production emitter constructs every line of this fixture.
#[cfg(feature = "measurements")]
pub fn measure_template(substitutions: usize) -> Result<String, Diagnostic> {
    use ir::{Binding, Expr, ExprKind, Function, Module, Statement, Type};
    let mut parts = Vec::new();
    let mut source = String::from("export function main():void {const a=`");
    for i in 0..=substitutions {
        source.push_str(&format!("x{i}"));
        parts.push(Expr {
            flow: None,
            bare_true: false,
            start: 0,
            ty: Type::String,
            kind: ExprKind::String(format!("x{i}")),
        });
        if i < substitutions {
            source.push_str(&format!("${{{i}}}"));
            parts.push(Expr {
                flow: None,
                bare_true: false,
                start: 0,
                ty: Type::Number,
                kind: ExprKind::Number(i as f64),
            });
        }
    }
    source.push_str("`;}");
    let mut types = ir::Types::new();
    let main_type = types.intern(vec![], Type::Void, 0);
    emitter::emit(
        &Module {
            hosts: vec![],
            exceptions: false,
            asynchronous: false,
            types,
            methods: Default::default(),
            captured: vec![true, false],
            bindings: vec![
                Binding {
                    ty: Some(main_type),
                    owner: 0,
                    start: 0,
                    end: 0,
                    mutable: false,
                    declaration: true,
                },
                Binding {
                    ty: Some(Type::String),
                    owner: 1,
                    start: 1,
                    end: 1,
                    mutable: false,
                    declaration: false,
                },
            ],
            functions: vec![Function {
                asynchronous: false,
                initializers: vec![],
                binding: 0,
                name: "main".into(),
                exported: true,
                parameters: vec![],
                result: Type::Void,
                body: vec![Statement::Block(vec![
                    Statement::Entry(vec![1]),
                    Statement::Declare(
                        1,
                        Expr {
                            flow: None,
                            bare_true: false,
                            start: 0,
                            ty: Type::String,
                            kind: ExprKind::Template(parts),
                        },
                    ),
                ])],
            }],
            body: vec![Statement::Entry(vec![0]), Statement::Function(0)],
            depth: DEPTH_CEILING,
            source: source.into_bytes(),
        },
        OUTPUT_FACTOR,
    )
}

fn compile_observed(
    source: &[u8],
    limits: Limits,
    grants: &[HostSignature],
    output_factor: usize,
    emission: fn(&ir::Module, usize) -> Result<String, Diagnostic>,
    mut observer: impl FnMut(&'static str, bool),
) -> Result<Compiled, Diagnostic> {
    let max_source = limits.max_source_bytes.min(SOURCE_CEILING);
    if source.len() as u64 > max_source {
        return Err(Diagnostic::at(
            source,
            max_source as usize,
            "limit:source-bytes",
            "Source byte limit exceeded",
        ));
    }
    let text = std::str::from_utf8(source)
        .map_err(|e| Diagnostic::at(source, e.valid_up_to(), "syntax", "Source is not UTF-8"))?;
    let max_depth = limits.max_nesting_depth.min(DEPTH_CEILING);
    let allocator = Allocator::default();
    observer("parse", true);
    let parsed = Parser::new(&allocator, text, SourceType::ts().with_module(true))
        .with_options(ParseOptions {
            max_nesting_depth: Some(max_depth as usize),
            ..ParseOptions::default()
        })
        .parse();
    observer("parse", false);
    if let Some(offset) = parsed.depth_exceeded {
        return Err(Diagnostic::at(
            source,
            offset as usize,
            "limit:nesting-depth",
            "Parser depth limit exceeded",
        ));
    }
    if let Some(error) = parsed.diagnostics.first() {
        let offset = error.labels.first().map_or(0, |label| label.offset());
        let message = error.to_string();
        // The parser reports module-reserved await with its async-context diagnostic.
        let code = if message == "Cannot use `await` as an identifier in an async context" {
            "C11"
        } else if message
            == "`await` is only allowed within async functions and at the top levels of modules"
        {
            "C19"
        } else {
            "syntax"
        };
        return Err(Diagnostic::at(source, offset as usize, code, message));
    }
    depth::check(&parsed.program, max_depth, source)?;
    observer("check", true);
    let module = checker::check_with_grants(&parsed.program, source, max_depth, grants);
    observer("check", false);
    let module = module?;
    for f in module.functions.iter().filter(|f| f.exported) {
        if !matches!(
            module.types.promise_value(f.result).unwrap_or(f.result),
            ir::Type::Void | ir::Type::Number | ir::Type::Boolean | ir::Type::String
        ) || f.parameters.iter().any(|(id, _)| {
            !matches!(
                module.bindings[*id].ty,
                Some(ir::Type::Number | ir::Type::Boolean | ir::Type::String)
            )
        }) {
            return Err(Diagnostic::at(
                source,
                module.bindings[f.binding].start as usize,
                "unsupported",
                "Host exports require scalar values",
            ));
        }
    }
    observer("emit", true);
    let luau = emission(&module, output_factor);
    observer("emit", false);
    Ok(Compiled {
        hosts: module.hosts.iter().map(|(_, n)| n.clone()).collect(),
        luau: luau?,
        exports: module
            .functions
            .iter()
            .filter(|f| f.exported)
            .map(|f| Export {
                name: f.name.clone(),
                parameters: f
                    .parameters
                    .iter()
                    .filter_map(|(id, _)| module.bindings[*id].ty.as_ref().map(ir::Type::tag))
                    .collect(),
                result: module
                    .types
                    .promise_value(f.result)
                    .unwrap_or(f.result)
                    .tag(),
            })
            .collect(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    const HELLO: &[u8] = b"export function main(): void { print(\"hello\"); }";
    #[cfg(feature = "measurements")]
    #[test]
    fn template_fixture_matches_the_checked_form() {
        let checked = compile(
            b"export function main():void {const a=`x0${0}x1`;}",
            Limits::default(),
        )
        .unwrap();
        assert_eq!(measure_template(1).unwrap(), checked.luau);
    }
    #[test]
    fn compile_a01_and_reject_other_shapes() {
        let result = compile(HELLO, Limits::default()).unwrap();
        assert!(result.luau.starts_with("--!strict\n"));
        assert_eq!(result.exports[0].name, "main");
        assert!(compile(b"export function main(): void {}", Limits::default()).is_ok());
        assert_eq!(
            compile(
                b"export function main(): void { print(1); }",
                Limits::default()
            )
            .unwrap_err()
            .code,
            "C1"
        );
        assert_eq!(
            compile(
                b"export function main<T>(): void { print('x'); }",
                Limits::default()
            )
            .unwrap_err()
            .code,
            "C8"
        );
        assert!(compile(b"", Limits::default()).unwrap().exports.is_empty());
        assert_eq!(
            compile(
                b"export async function main(): void { print('x'); }",
                Limits::default()
            )
            .unwrap_err()
            .code,
            "C19"
        );
    }
    #[test]
    fn limits_and_locations() {
        let e = compile(b"\n\xff", Limits::default()).unwrap_err();
        assert_eq!((e.code, e.offset, e.line, e.column), ("syntax", 1, 2, 1));
        let e = compile(
            HELLO,
            Limits {
                max_source_bytes: 0,
                ..Limits::default()
            },
        )
        .unwrap_err();
        assert_eq!(e.code, "limit:source-bytes");
        assert_eq!(
            compile(
                HELLO,
                Limits {
                    max_nesting_depth: 0,
                    ..Limits::default()
                }
            )
            .unwrap_err()
            .code,
            "limit:nesting-depth"
        );
        assert_eq!(
            compile(b"export function {", Limits::default())
                .unwrap_err()
                .code,
            "syntax"
        );
        for chain in [
            "1+".repeat(160) + "1",
            "f".to_string() + &"()".repeat(160),
            "a".to_string() + &".b".repeat(160),
        ] {
            let source = format!("export function main(): void {{ print({chain}); }}");
            assert_eq!(
                compile(source.as_bytes(), Limits::default())
                    .unwrap_err()
                    .code,
                "limit:nesting-depth"
            );
        }
        let source = format!(
            "export function main(): void {{ print({}'x'{}); }}",
            "(".repeat(160),
            ")".repeat(160)
        );
        assert_eq!(
            compile(source.as_bytes(), Limits::default())
                .unwrap_err()
                .code,
            "limit:nesting-depth"
        );
    }
    #[test]
    fn decoded_strings() {
        let result = compile(
            r#"export function main(): void { print("\x00\r\n\"\\é"); }"#.as_bytes(),
            Limits::default(),
        )
        .unwrap();
        assert!(result.luau.contains(r#""\000\013\010\034\092\195\169""#));
        for value in [r"\uD800", r"\u{D800}"] {
            let source = format!("export function main(): void {{ print(\"{value}\"); }}");
            assert_eq!(
                compile(source.as_bytes(), Limits::default())
                    .unwrap_err()
                    .code,
                "C5"
            );
        }
    }
}

