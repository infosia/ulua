//! The sampled witnesses of pipeline.md §9.3: stock `tsc` with the prelude and the host
//! declarations, and `luau-analyze -j1` over the generated Luau. One process per batch.
use crate::check::Failure;
use std::{
    collections::BTreeMap,
    io::Read,
    path::{Path, PathBuf},
    process::{Command, Output, Stdio},
    time::{Duration, Instant},
};

/// One accepted input of the sample.
#[derive(Clone)]
pub struct Sample {
    /// The input index.
    pub index: u64,
    /// The source.
    pub source: Vec<u8>,
    /// The grants of the compile.
    pub signatures: Vec<ulua_compiler::HostSignature>,
    /// The generated Luau.
    pub luau: String,
}

fn type_name(tag: u32) -> &'static str {
    match tag {
        1 => "number",
        2 => "boolean",
        3 => "string",
        _ => "void",
    }
}

/// The host declarations of a grant list in the format of abi.md §6.3.
pub fn declarations(grants: &[ulua_compiler::HostSignature]) -> String {
    let mut out = String::from("// Ulua host declarations. Generated by ulua_declarations.\n");
    for g in grants {
        let params: Vec<_> = g
            .parameters
            .iter()
            .enumerate()
            .map(|(i, t)| format!("p{i}: {}", type_name(*t)))
            .collect();
        let result = type_name(g.result);
        let result = if g.asynchronous {
            format!("Promise<{result}>")
        } else {
            result.to_owned()
        };
        out.push_str(&format!(
            "declare function {}({}): {result};\n",
            g.name,
            params.join(", ")
        ));
    }
    out
}

/// CLAUDE.md invariant 3: the `tsc` codes outside the rule. TS2563 and TS2321 are `tsc`
/// resource limits; TS2367 and TS2845 are the equality codes of collisions.md C7 (the
/// CLI gives no node, so the code stands for the position); a message that names the
/// type `never` is the narrowing of an accepted equality, null test, or null assignment.
pub fn exempt(code: u32, message: &str) -> bool {
    matches!(code, 2563 | 2321 | 2367 | 2845)
        || message.contains("type 'never'")
        || message.contains("Type 'never'")
}

struct Diagnostic {
    file: String,
    code: u32,
    message: String,
}

/// Parse `tsc` output: `file(line,col): error TSnnnn: message` and indented continuations.
fn parse_tsc(text: &str) -> Result<Vec<Diagnostic>, String> {
    let mut out: Vec<Diagnostic> = vec![];
    for line in text.lines() {
        if line.starts_with(' ') {
            if let Some(last) = out.last_mut() {
                last.message.push('\n');
                last.message.push_str(line.trim());
            }
            continue;
        }
        if line.trim().is_empty() || line.starts_with("Found ") {
            continue;
        }
        let Some((head, rest)) = line.split_once(": error TS") else {
            return Err(format!("unparsed tsc line: {line}"));
        };
        let (code, message) = rest.split_once(": ").unwrap_or((rest, ""));
        let file = head.split('(').next().unwrap_or(head).to_owned();
        out.push(Diagnostic {
            file,
            code: code.parse().map_err(|_| format!("tsc code: {line}"))?,
            message: message.to_owned(),
        });
    }
    Ok(out)
}

fn case(index: u64) -> String {
    format!("case-{index}")
}

/// The deadline of one witness batch (pipeline.md §9.3).
pub const DEADLINE: Duration = Duration::from_secs(30);

/// The witness commands and their deadline. Tests replace the commands with stubs.
pub struct Tools {
    /// The repository root: `prelude/`, `tsconfig.json`, `node_modules/`.
    pub root: PathBuf,
    /// The `tsc` program and its leading arguments; `-p <config>` follows.
    pub tsc: Vec<String>,
    /// The `luau-analyze` program and its leading arguments; the files follow.
    pub analyze: Vec<String>,
    /// The deadline of each process.
    pub deadline: Duration,
}

impl Tools {
    /// The stock tools of the repository.
    pub fn new(root: &Path) -> Self {
        Self {
            root: root.to_path_buf(),
            tsc: vec![
                "node".into(),
                root.join("node_modules/typescript/bin/tsc")
                    .display()
                    .to_string(),
            ],
            analyze: vec![
                root.join(format!(
                    "target/luau-tools/luau-analyze{}",
                    std::env::consts::EXE_SUFFIX
                ))
                .display()
                .to_string(),
                "-j1".into(),
            ],
            deadline: DEADLINE,
        }
    }
}

/// The output of a process, or `None` when it passed the deadline and was killed.
pub fn run_with_deadline(cmd: &mut Command, deadline: Duration) -> Result<Option<Output>, String> {
    let mut child = cmd
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("{cmd:?}: {e}"))?;
    let read = |pipe: Option<Box<dyn Read + Send>>| {
        std::thread::spawn(move || {
            let mut bytes = vec![];
            if let Some(mut p) = pipe {
                let _ = p.read_to_end(&mut bytes);
            }
            bytes
        })
    };
    let out = read(
        child
            .stdout
            .take()
            .map(|p| Box::new(p) as Box<dyn Read + Send>),
    );
    let err = read(
        child
            .stderr
            .take()
            .map(|p| Box::new(p) as Box<dyn Read + Send>),
    );
    let started = Instant::now();
    let status = loop {
        if let Some(status) = child.try_wait().map_err(|e| e.to_string())? {
            break status;
        }
        if started.elapsed() >= deadline {
            let _ = child.kill();
            let _ = child.wait();
            return Ok(None);
        }
        std::thread::sleep(Duration::from_millis(20));
    };
    Ok(Some(Output {
        status,
        stdout: out.join().unwrap_or_default(),
        stderr: err.join().unwrap_or_default(),
    }))
}

/// The result of a witness check: failures, and witness resource limits (a deadline or a
/// `tsc` stack overflow, outside invariant 3), each with its input index.
#[derive(Default, Debug)]
pub struct Checked {
    /// The failures.
    pub failures: Vec<(u64, Failure)>,
    /// The witness resource limits: index and a description.
    pub limits: Vec<(u64, String)>,
}

/// One `tsc` process over one group. `None` is a resource limit of the group.
fn tsc_group(
    tools: &Tools,
    dir: &Path,
    n: usize,
    decl: &str,
    group: &[&Sample],
) -> Result<Option<Vec<(u64, Failure)>>, String> {
    let root = &tools.root;
    let mut files: Vec<PathBuf> = vec![root.join("prelude/ulua.d.ts")];
    if group.iter().any(|s| !s.signatures.is_empty()) {
        let host = dir.join(format!("host-{n}.d.ts"));
        std::fs::write(&host, decl).map_err(|e| e.to_string())?;
        files.push(host);
    }
    for s in group {
        // pipeline.md §3.3: the compiler parses a module; the marker gives `tsc` the
        // same goal, so the files of one batch do not share a global scope.
        let mut text = s.source.clone();
        text.extend_from_slice(b"\nexport {};\n");
        let path = dir.join(format!("{}.ts", case(s.index)));
        std::fs::write(&path, text).map_err(|e| e.to_string())?;
        files.push(path);
    }
    // The options of tsconfig.json, as tools/witness/corpus.mjs uses them; only the files differ.
    let quoted: Vec<String> = files
        .iter()
        .map(|f| format!("{:?}", f.display().to_string()))
        .collect();
    let config = dir.join(format!("tsconfig-{n}.json"));
    let text = format!(
        "{{\"extends\": {:?}, \"files\": [{}], \"include\": []}}\n",
        root.join("tsconfig.json").display().to_string(),
        quoted.join(", ")
    );
    std::fs::write(&config, text).map_err(|e| e.to_string())?;
    let mut cmd = Command::new(&tools.tsc[0]);
    cmd.current_dir(root)
        .args(&tools.tsc[1..])
        .arg("-p")
        .arg(&config);
    let Some(out) = run_with_deadline(&mut cmd, tools.deadline)? else {
        return Ok(None);
    };
    let stderr = String::from_utf8_lossy(&out.stderr);
    if stderr.contains("Maximum call stack size exceeded") {
        // A `tsc` stack overflow is outside invariant 3.
        return Ok(None);
    }
    let stdout = String::from_utf8_lossy(&out.stdout);
    if !out.status.success() && out.status.code() != Some(2) {
        return Err(format!("tsc exited with {}: {stderr}{stdout}", out.status));
    }
    let mut failures = vec![];
    for d in parse_tsc(&stdout)? {
        let Some(s) = group
            .iter()
            .find(|s| d.file.ends_with(&format!("{}.ts", case(s.index))))
        else {
            return Err(format!(
                "tsc diagnostic outside the cases: {} TS{} {}",
                d.file, d.code, d.message
            ));
        };
        if !exempt(d.code, &d.message) {
            failures.push((
                s.index,
                Failure {
                    key: format!("witness:tsc:TS{}", d.code),
                    detail: format!("tsc TS{}: {}", d.code, d.message),
                },
            ));
        }
    }
    Ok(Some(failures))
}

fn tsc(tools: &Tools, dir: &Path, samples: &[Sample], out: &mut Checked) -> Result<(), String> {
    let mut groups: BTreeMap<String, Vec<&Sample>> = BTreeMap::new();
    for s in samples {
        groups
            .entry(declarations(&s.signatures))
            .or_default()
            .push(s);
    }
    let mut n = 0;
    for (decl, group) in &groups {
        n += 1;
        if let Some(f) = tsc_group(tools, dir, n, decl, group)? {
            out.failures.extend(f);
            continue;
        }
        // The batch passed a resource limit: check each input again on its own.
        for s in group {
            n += 1;
            match tsc_group(tools, dir, n, decl, std::slice::from_ref(s))? {
                Some(f) => out.failures.extend(f),
                None => out.limits.push((
                    s.index,
                    "tsc passed its deadline or its stack (invariant 3)".into(),
                )),
            }
        }
    }
    Ok(())
}

/// One `luau-analyze` process. `None` is a deadline.
fn analyze_batch(
    tools: &Tools,
    dir: &Path,
    samples: &[&Sample],
) -> Result<Option<Vec<(u64, Failure)>>, String> {
    let mut paths = vec![];
    for s in samples {
        let p = dir.join(format!("{}.luau", case(s.index)));
        std::fs::write(&p, &s.luau).map_err(|e| e.to_string())?;
        paths.push(p);
    }
    let mut cmd = Command::new(&tools.analyze[0]);
    cmd.args(&tools.analyze[1..]).args(&paths);
    let Some(out) = run_with_deadline(&mut cmd, tools.deadline)? else {
        return Ok(None);
    };
    if out.status.success() {
        return Ok(Some(vec![]));
    }
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    let mut failures = vec![];
    for s in samples {
        let name = format!("{}.luau", case(s.index));
        let lines: Vec<_> = text.lines().filter(|l| l.contains(&name)).collect();
        if !lines.is_empty() {
            let first = lines[0].split_once("): ").map_or(lines[0], |(_, m)| m);
            let kind = first.split(':').next().unwrap_or("error");
            failures.push((
                s.index,
                Failure {
                    key: format!("witness:luau-analyze:{kind}"),
                    detail: lines.join("\n"),
                },
            ));
        }
    }
    if failures.is_empty() {
        // An exit without an attributable line fails every input of the batch.
        for s in samples {
            failures.push((
                s.index,
                Failure {
                    key: "witness:luau-analyze:exit".into(),
                    detail: format!("luau-analyze {}: {text}", out.status),
                },
            ));
        }
    }
    Ok(Some(failures))
}

fn analyze(tools: &Tools, dir: &Path, samples: &[Sample], out: &mut Checked) -> Result<(), String> {
    if !Path::new(&tools.analyze[0]).is_file() {
        return Err(format!(
            "{} is absent; run sh tools/luau-tools.sh",
            tools.analyze[0]
        ));
    }
    let all: Vec<&Sample> = samples.iter().collect();
    if let Some(f) = analyze_batch(tools, dir, &all)? {
        out.failures.extend(f);
        return Ok(());
    }
    for s in &all {
        match analyze_batch(tools, dir, std::slice::from_ref(s))? {
            Some(f) => out.failures.extend(f),
            None => out
                .limits
                .push((s.index, "luau-analyze passed its deadline".into())),
        }
    }
    Ok(())
}

/// Check one batch with both witnesses. A tool error (a missing tool, an unparsed line)
/// is an error of the run, not a failure of an input.
pub fn check(tools: &Tools, samples: &[Sample]) -> Result<Checked, String> {
    let mut out = Checked::default();
    if samples.is_empty() {
        return Ok(out);
    }
    static COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let dir = tools
        .root
        .join("target/fuzz/tmp")
        .join(format!("witness-{}-{n}", std::process::id()));
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let result =
        tsc(tools, &dir, samples, &mut out).and_then(|()| analyze(tools, &dir, samples, &mut out));
    let _ = std::fs::remove_dir_all(&dir);
    result.map(|()| out)
}

#[cfg(test)]
mod tests {
    use super::*;
    fn root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }
    fn sample(index: u64, source: &str, luau: &str) -> Sample {
        Sample {
            index,
            source: source.as_bytes().to_vec(),
            signatures: vec![],
            luau: luau.to_owned(),
        }
    }
    #[test]
    fn exempt_codes_follow_invariant_3() {
        assert!(exempt(2367, "This comparison appears to be unintentional"));
        assert!(exempt(2322, "Type 'never' is not assignable"));
        assert!(!exempt(
            2322,
            "Type 'string' is not assignable to type 'number'."
        ));
    }
    #[test]
    fn injected_witness_violations_are_failures() {
        // Seeded violations: a source that tsc rejects, and Luau that strict analysis rejects.
        let good = "--!strict\nlocal x: number = 1\nprint(x)\n";
        let samples = [
            sample(1, "export function main(): void { print('a'); }", good),
            sample(
                2,
                "let x: number = 'text'; export function main(): void {}",
                good,
            ),
            sample(
                3,
                "export function main(): void {}",
                "--!strict\nlocal y: number = \"s\"\n",
            ),
        ];
        let failures = check(&Tools::new(&root()), &samples).unwrap().failures;
        let keys: Vec<_> = failures.iter().map(|(i, f)| (*i, f.key.as_str())).collect();
        assert!(keys.contains(&(2, "witness:tsc:TS2322")), "{keys:?}");
        assert!(
            keys.iter()
                .any(|(i, k)| *i == 3 && k.starts_with("witness:luau-analyze"))
        );
        assert!(!keys.iter().any(|(i, _)| *i == 1), "{keys:?}");
    }
    #[test]
    fn host_declarations_reach_tsc() {
        let mut s = sample(
            4,
            "// grants: hostLater\nexport async function main(): Promise<void> { print(`${await hostLater(1)}`); }",
            "--!strict\n",
        );
        s.signatures = crate::seeds::grants(&s.source);
        let c = check(&Tools::new(&root()), &[s]).unwrap();
        assert!(c.failures.is_empty() && c.limits.is_empty(), "{c:?}");
    }
    #[test]
    fn a_witness_past_its_deadline_is_a_limit_and_the_batch_is_checked_again() {
        // A stub tsc that never ends within the deadline; the analyzer is a stub that passes.
        let mut tools = Tools::new(&root());
        let node = Command::new("node")
            .args(["-p", "process.execPath"])
            .output()
            .unwrap();
        assert!(node.status.success());
        let node = String::from_utf8(node.stdout).unwrap().trim().to_owned();
        let calls = root().join(format!(
            "target/witness-deadline-{}.log",
            std::process::id()
        ));
        let _ = std::fs::remove_file(&calls);
        let slow = format!(
            "require('fs').appendFileSync({:?}, 'call\\n'); setTimeout(() => {{}}, 20000)",
            calls.display().to_string()
        );
        tools.tsc = vec![node.clone(), "-e".into(), slow.clone(), "--".into()];
        tools.analyze = vec![
            node.clone(),
            "-e".into(),
            "process.exit(0)".into(),
            "--".into(),
        ];
        tools.deadline = Duration::from_millis(500);
        let samples = [
            sample(5, "export function main(): void {}", "--!strict\n"),
            sample(6, "export function f(): void {}", "--!strict\n"),
        ];
        let c = check(&tools, &samples).unwrap();
        assert!(c.failures.is_empty(), "{c:?}");
        let limited: Vec<_> = c.limits.iter().map(|l| l.0).collect();
        assert_eq!(limited, [5, 6]);
        // One batch run and one run per input, each killed at the deadline.
        assert_eq!(std::fs::read_to_string(&calls).unwrap().lines().count(), 3);
        std::fs::write(&calls, "").unwrap();
        // A stub analyzer past its deadline gives the same record.
        let mut tools = Tools::new(&root());
        tools.analyze = vec![node, "-e".into(), slow, "--".into()];
        tools.deadline = Duration::from_millis(500);
        let mut out = Checked::default();
        let dir = root().join("target/fuzz/tmp/witness-test-analyze");
        std::fs::create_dir_all(&dir).unwrap();
        analyze(&tools, &dir, &samples[..1], &mut out).unwrap();
        assert_eq!(out.limits.iter().map(|l| l.0).collect::<Vec<_>>(), [5]);
        assert_eq!(std::fs::read_to_string(&calls).unwrap().lines().count(), 2);
        std::fs::remove_file(calls).unwrap();
        std::fs::remove_dir_all(dir).unwrap();
    }
}
