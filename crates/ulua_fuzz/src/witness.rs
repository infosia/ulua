//! The sampled witnesses of pipeline.md §9.3: stock `tsc` with the prelude and the host
//! declarations, and `luau-analyze -j1` over the generated Luau. One process per batch.
use crate::check::Failure;
use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
    process::Command,
};

/// One accepted input of the sample.
#[derive(Clone)]
pub struct Sample {
    /// The input index.
    pub index: u64,
    /// The source.
    pub source: Vec<u8>,
    /// The grants of the compile.
    pub signatures: Vec<ulua_compiler::HostSignature>,
    /// The generated Luau.
    pub luau: String,
}

fn type_name(tag: u32) -> &'static str {
    match tag {
        1 => "number",
        2 => "boolean",
        3 => "string",
        _ => "void",
    }
}

/// The host declarations of a grant list in the format of abi.md §6.3.
pub fn declarations(grants: &[ulua_compiler::HostSignature]) -> String {
    let mut out = String::from("// Ulua host declarations. Generated by ulua_declarations.\n");
    for g in grants {
        let params: Vec<_> = g
            .parameters
            .iter()
            .enumerate()
            .map(|(i, t)| format!("p{i}: {}", type_name(*t)))
            .collect();
        let result = type_name(g.result);
        let result = if g.asynchronous {
            format!("Promise<{result}>")
        } else {
            result.to_owned()
        };
        out.push_str(&format!(
            "declare function {}({}): {result};\n",
            g.name,
            params.join(", ")
        ));
    }
    out
}

/// CLAUDE.md invariant 3: the `tsc` codes outside the rule. TS2563 and TS2321 are `tsc`
/// resource limits; TS2367 and TS2845 are the equality codes of collisions.md C7 (the
/// CLI gives no node, so the code stands for the position); a message that names the
/// type `never` is the narrowing of an accepted equality, null test, or null assignment.
pub fn exempt(code: u32, message: &str) -> bool {
    matches!(code, 2563 | 2321 | 2367 | 2845)
        || message.contains("type 'never'")
        || message.contains("Type 'never'")
}

struct Diagnostic {
    file: String,
    code: u32,
    message: String,
}

/// Parse `tsc` output: `file(line,col): error TSnnnn: message` and indented continuations.
fn parse_tsc(text: &str) -> Result<Vec<Diagnostic>, String> {
    let mut out: Vec<Diagnostic> = vec![];
    for line in text.lines() {
        if line.starts_with(' ') {
            if let Some(last) = out.last_mut() {
                last.message.push('\n');
                last.message.push_str(line.trim());
            }
            continue;
        }
        if line.trim().is_empty() || line.starts_with("Found ") {
            continue;
        }
        let Some((head, rest)) = line.split_once(": error TS") else {
            return Err(format!("unparsed tsc line: {line}"));
        };
        let (code, message) = rest.split_once(": ").unwrap_or((rest, ""));
        let file = head.split('(').next().unwrap_or(head).to_owned();
        out.push(Diagnostic {
            file,
            code: code.parse().map_err(|_| format!("tsc code: {line}"))?,
            message: message.to_owned(),
        });
    }
    Ok(out)
}

fn case(index: u64) -> String {
    format!("case-{index}")
}

fn tsc(root: &Path, dir: &Path, samples: &[Sample]) -> Result<Vec<(u64, Failure)>, String> {
    let mut groups: BTreeMap<String, Vec<&Sample>> = BTreeMap::new();
    for s in samples {
        groups
            .entry(declarations(&s.signatures))
            .or_default()
            .push(s);
    }
    let mut failures = vec![];
    for (n, (decl, group)) in groups.iter().enumerate() {
        let mut args: Vec<PathBuf> = vec![root.join("prelude/ulua.d.ts")];
        if group.iter().any(|s| !s.signatures.is_empty()) {
            let host = dir.join(format!("host-{n}.d.ts"));
            std::fs::write(&host, decl).map_err(|e| e.to_string())?;
            args.push(host);
        }
        for s in group {
            // pipeline.md §3.3: the compiler parses a module; the marker gives `tsc` the
            // same goal, so the files of one batch do not share a global scope.
            let mut text = s.source.clone();
            text.extend_from_slice(b"\nexport {};\n");
            let path = dir.join(format!("{}.ts", case(s.index)));
            std::fs::write(&path, text).map_err(|e| e.to_string())?;
            args.push(path);
        }
        let out = Command::new("node")
            .current_dir(root)
            .args([
                "node_modules/typescript/bin/tsc",
                "--noEmit",
                "--strict",
                "--target",
                "es2022",
                "--module",
                "esnext",
                "--lib",
                "es2022",
            ])
            .args(&args)
            .output()
            .map_err(|e| format!("tsc: {e}"))?;
        let stderr = String::from_utf8_lossy(&out.stderr);
        if stderr.contains("Maximum call stack size exceeded") {
            // A `tsc` stack overflow is outside invariant 3.
            continue;
        }
        let stdout = String::from_utf8_lossy(&out.stdout);
        if !out.status.success() && out.status.code() != Some(2) {
            return Err(format!("tsc exited with {}: {stderr}{stdout}", out.status));
        }
        for d in parse_tsc(&stdout)? {
            let Some(s) = group
                .iter()
                .find(|s| d.file.ends_with(&format!("{}.ts", case(s.index))))
            else {
                return Err(format!(
                    "tsc diagnostic outside the cases: {} TS{} {}",
                    d.file, d.code, d.message
                ));
            };
            if !exempt(d.code, &d.message) {
                failures.push((
                    s.index,
                    Failure {
                        key: format!("witness:tsc:TS{}", d.code),
                        detail: format!("tsc TS{}: {}", d.code, d.message),
                    },
                ));
            }
        }
    }
    Ok(failures)
}

fn analyze(root: &Path, dir: &Path, samples: &[Sample]) -> Result<Vec<(u64, Failure)>, String> {
    let tool = root.join("target/luau-tools/luau-analyze");
    if !tool.is_file() {
        return Err(format!(
            "{} is absent; run sh tools/luau-tools.sh",
            tool.display()
        ));
    }
    let mut paths = vec![];
    for s in samples {
        let p = dir.join(format!("{}.luau", case(s.index)));
        std::fs::write(&p, &s.luau).map_err(|e| e.to_string())?;
        paths.push(p);
    }
    let out = Command::new(&tool)
        .arg("-j1")
        .args(&paths)
        .output()
        .map_err(|e| format!("luau-analyze: {e}"))?;
    if out.status.success() {
        return Ok(vec![]);
    }
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    let mut failures = vec![];
    for s in samples {
        let name = format!("{}.luau", case(s.index));
        let lines: Vec<_> = text.lines().filter(|l| l.contains(&name)).collect();
        if !lines.is_empty() {
            let first = lines[0].split_once("): ").map_or(lines[0], |(_, m)| m);
            let kind = first.split(':').next().unwrap_or("error");
            failures.push((
                s.index,
                Failure {
                    key: format!("witness:luau-analyze:{kind}"),
                    detail: lines.join("\n"),
                },
            ));
        }
    }
    if failures.is_empty() {
        // An exit without an attributable line fails every input of the batch.
        for s in samples {
            failures.push((
                s.index,
                Failure {
                    key: "witness:luau-analyze:exit".into(),
                    detail: format!("luau-analyze {}: {text}", out.status),
                },
            ));
        }
    }
    Ok(failures)
}

/// Check one batch with both witnesses. A tool error (a missing tool, an unparsed line)
/// is an error of the run, not a failure of an input.
pub fn check(root: &Path, samples: &[Sample]) -> Result<Vec<(u64, Failure)>, String> {
    if samples.is_empty() {
        return Ok(vec![]);
    }
    static COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let dir = root
        .join("target/fuzz/tmp")
        .join(format!("witness-{}-{n}", std::process::id()));
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let result = tsc(root, &dir, samples).and_then(|mut f| {
        f.extend(analyze(root, &dir, samples)?);
        Ok(f)
    });
    let _ = std::fs::remove_dir_all(&dir);
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    fn root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }
    fn sample(index: u64, source: &str, luau: &str) -> Sample {
        Sample {
            index,
            source: source.as_bytes().to_vec(),
            signatures: vec![],
            luau: luau.to_owned(),
        }
    }
    #[test]
    fn exempt_codes_follow_invariant_3() {
        assert!(exempt(2367, "This comparison appears to be unintentional"));
        assert!(exempt(2322, "Type 'never' is not assignable"));
        assert!(!exempt(
            2322,
            "Type 'string' is not assignable to type 'number'."
        ));
    }
    #[test]
    fn injected_witness_violations_are_failures() {
        // Seeded violations: a source that tsc rejects, and Luau that strict analysis rejects.
        let good = "--!strict\nlocal x: number = 1\nprint(x)\n";
        let samples = [
            sample(1, "export function main(): void { print('a'); }", good),
            sample(
                2,
                "let x: number = 'text'; export function main(): void {}",
                good,
            ),
            sample(
                3,
                "export function main(): void {}",
                "--!strict\nlocal y: number = \"s\"\n",
            ),
        ];
        let failures = check(&root(), &samples).unwrap();
        let keys: Vec<_> = failures.iter().map(|(i, f)| (*i, f.key.as_str())).collect();
        assert!(keys.contains(&(2, "witness:tsc:TS2322")), "{keys:?}");
        assert!(
            keys.iter()
                .any(|(i, k)| *i == 3 && k.starts_with("witness:luau-analyze"))
        );
        assert!(!keys.iter().any(|(i, _)| *i == 1), "{keys:?}");
    }
    #[test]
    fn host_declarations_reach_tsc() {
        let mut s = sample(
            4,
            "// grants: hostLater\nexport async function main(): Promise<void> { print(`${await hostLater(1)}`); }",
            "--!strict\n",
        );
        s.signatures = crate::seeds::grants(&s.source);
        assert!(check(&root(), &[s]).unwrap().is_empty());
    }
}
